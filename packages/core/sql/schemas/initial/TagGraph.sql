-- 5. Cross-Entity Associations
-- ============================================================================
-- v1 -> v2: association_types -> association_type,
--           association_type_category_pairs -> association_type_category_pair,
--           tag_associations -> tag_association

-- 5.1 Association vocabulary (born_in, dwelt_in, authored, ...)
CREATE TABLE association_type (
    id              TEXT PRIMARY KEY,               -- Type slug: 'born_in', 'authored'
    name            TEXT NOT NULL,                  -- Label read entity_1 -> entity_2: "born in"
    reciprocal_name TEXT,                           -- Label when read in the other direction
                                                    -- ("birthplace of"). Just wording.
    reciprocal_id   TEXT REFERENCES association_type(id),  -- The type that IS this one reversed, when a
                                                    -- distinct type exists for it. Distinct from
                                                    -- reciprocal_name, which only renames this type;
                                                    -- self-referential for symmetric types.
    notes           TEXT                            -- Prose describing the association type
);

-- 5.2 Which category pairs a type is valid for ('people' x 'places', ...)
CREATE TABLE association_type_category_pair (
    association_type_id TEXT NOT NULL REFERENCES association_type(id),  -- The type being constrained
    entity_1_category   TEXT NOT NULL,              -- Allowed category of the subject end:
                                                    -- people|places|objects|themes
    entity_2_category   TEXT NOT NULL,              -- Allowed category of the object end. 'born_in'
                                                    -- admits ('people','places') and nothing else.
                                                    -- Advisory only -- tag_association has no FK to
                                                    -- this table; scripts/validate-module.js checks it.

    PRIMARY KEY (association_type_id, entity_1_category, entity_2_category)
);

-- 5.3 The association edges themselves.
-- Polymorphic: (entity_N_category, entity_N_id) points at person/place/object/theme.
-- No FK is possible on a polymorphic reference; integrity is checked by
-- scripts/validate-module.js.
CREATE TABLE tag_association (
    id                  TEXT PRIMARY KEY,           -- Edge slug. entity_verse_link rows cite it as
                                                    -- source_id with source_type='tag_association'.
    entity_1_id         TEXT NOT NULL,              -- Subject end: the slug. Which TABLE it lives in is
                                                    -- decided by entity_1_category -- the two columns
                                                    -- are one polymorphic reference and no FK can
                                                    -- express it.
    entity_1_category   TEXT NOT NULL,              -- people|places|objects|themes (open set, validated
                                                    -- in TypeScript). Plural, because it names a
                                                    -- category as DATA, not a table.
    entity_2_id         TEXT NOT NULL,              -- Object end: the slug
    entity_2_category   TEXT NOT NULL,              -- Object end: its category, as above
    association_type_id TEXT REFERENCES association_type(id),  -- What kind of edge. NULL for an
                                                    -- association the builder found but could not
                                                    -- classify -- e.g. bare co-occurrence.
    strength            REAL CHECK (strength BETWEEN 0.0 AND 1.0),  -- How strongly the two are linked,
                                                    -- 0.0-1.0. Closed numeric domain, so the CHECK is
                                                    -- kept. Distinct from `confidence`: strength is how
                                                    -- STRONG the link is, confidence is how SURE we are
                                                    -- it exists. A co-occurrence may be certain and
                                                    -- weak; an inference, strong and disputed.
    confidence          TEXT,                       -- How sure we are the association is real (as
                                                    -- opposed to `strength` above -- see it). Open set,
                                                    -- no CHECK, same vocabulary as
                                                    -- person_relationship.confidence:
                                                    --   'certain'   Stated plainly in the text
                                                    --   'probable'  Strongly implied
                                                    --   'possible'  Supportable but not established
                                                    --   'disputed'  Interpreters disagree
                                                    --   'derived'   Inferred by the build, not by a
                                                    --               reader -- machine-generated
    source              TEXT,                       -- What produced the row. Open set, no CHECK:
                                                    --   'seeded'        Authored by hand in the
                                                    --                   taxonomy JSON sources
                                                    --   'cooccurrence'  Derived by build-tag-graph.js
                                                    --                   from entities appearing in the
                                                    --                   same passages
                                                    --   'llm'           Proposed by enrich-tag-graph-
                                                    --                   llm.js
                                                    -- Lets a consumer show or hide machine-derived
                                                    -- edges. Pairs with `confidence`: a 'cooccurrence'
                                                    -- edge is typically 'derived'.
    notes               TEXT,                       -- Prose about the association
    metadata            TEXT                        -- JSON: anything not modelled above
);

CREATE INDEX idx_tag_association_e1 ON tag_association(entity_1_id, entity_1_category);
CREATE INDEX idx_tag_association_e2 ON tag_association(entity_2_id, entity_2_category);
CREATE INDEX idx_tag_association_type ON tag_association(association_type_id);

