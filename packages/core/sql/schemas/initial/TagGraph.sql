-- ============================================================================
-- THE FOUR-FAMILY PATTERN (sections 1-4)
-- ============================================================================
-- People, places, objects and themes are modelled identically, so the tables in
-- sections 1-4 repeat one shape four times. Learn it once:
--
--   <family>                 The entity itself. `id` is a slug, `name` is the
--                            display label, `notes` is prose for a reader.
--   <family>_alias           Alternate names that should resolve to the entity
--                            ("Saul of Tarsus" -> paul). Many per entity.
--   <family>_attribute       A self-nesting taxonomy of properties, its own rows
--   (person_role for people) referencing their `parent_id`.
--   <family>_attribute_map   Which entities carry which attributes. A join
--   (person_role_map)        table; its composite PRIMARY KEY is the whole row.
--
-- Two conventions hold throughout:
--
--   * Every `id` is TEXT -- a stable, human-readable slug ('david',
--     'mount_sinai'), not a number. The taxonomy JSON sources use slugs, the
--     polymorphic association columns store them, and the repository dispatches
--     on category -> table with them. A rebuild of the graph therefore produces
--     the same ids, so links into it survive.
--   * `parent_id` self-references make each taxonomy a tree of arbitrary depth,
--     walked with a recursive CTE. NULL parent = a root.
--
-- Only the per-family extras differ, and those carry their own comments below:
-- person has tribe/nation, place has modern_name, object has significance.

-- ============================================================================
-- 1. People
-- ============================================================================
-- v1 -> v2: person_roles -> person_role, people -> person, people_aliases ->
--           person_alias, people_roles -> person_role_map,
--           people_relationships -> person_relationship

-- 1.1 Role taxonomy (self-nesting: 'prophet' -> 'major_prophet')
CREATE TABLE person_role (
    id        TEXT PRIMARY KEY,                     -- Role slug: 'prophet', 'major_prophet'
    name      TEXT NOT NULL,                        -- Display label: "Major Prophet"
    parent_id TEXT REFERENCES person_role(id),      -- Broader role. NULL = a root of the taxonomy.
    notes     TEXT                                  -- Prose describing the role
);

-- 1.2 People
CREATE TABLE person (
    id       TEXT PRIMARY KEY,                      -- Slug: 'david', 'mary_mother_of_jesus'
    name     TEXT NOT NULL,                         -- Primary display name. Other names for the same
                                                    -- person are person_alias rows, not extra people.
    tribe    TEXT,                                  -- Israelite tribe, where the text names one:
                                                    -- 'judah', 'levi'. NULL for non-Israelites and
                                                    -- wherever scripture is silent.
    nation   TEXT,                                  -- People-group or nation: 'israel', 'moab'. Free
                                                    -- text, not a FK to `place`: a nation is not the
                                                    -- same thing as a location.
    notes    TEXT,                                  -- Prose about the person
    metadata TEXT                                   -- JSON: anything not modelled above
);

CREATE INDEX idx_person_name ON person(name COLLATE NOCASE);

-- 1.3 Alternate names ("Saul of Tarsus" -> paul)
CREATE TABLE person_alias (
    person_id TEXT NOT NULL REFERENCES person(id),  -- The person this name refers to
    alias     TEXT NOT NULL                         -- The alternate name. Indexed COLLATE NOCASE
                                                    -- below, so lookup is case-insensitive.
);

CREATE INDEX idx_person_alias_person ON person_alias(person_id);
CREATE INDEX idx_person_alias_alias ON person_alias(alias COLLATE NOCASE);

-- 1.4 Role assignment
CREATE TABLE person_role_map (
    person_id TEXT NOT NULL REFERENCES person(id),  -- Who holds the role
    role_id   TEXT NOT NULL REFERENCES person_role(id),  -- Which role. Many-to-many: a person may hold
                                                    -- several, and the pair is the whole row.

    PRIMARY KEY (person_id, role_id)
);

-- 1.5 Person-to-person relationships (father_of, wife_of, ...)
CREATE TABLE person_relationship (
    id                           TEXT PRIMARY KEY,  -- Relationship slug
    person_1_id                  TEXT NOT NULL REFERENCES person(id),  -- The subject: read the row as
                                                    -- "person_1 is <relationship_type> person_2".
    person_2_id                  TEXT NOT NULL REFERENCES person(id),  -- The object. Order matters --
                                                    -- reading the other way needs
                                                    -- relationship_type_reciprocal.
    relationship_type            TEXT NOT NULL,     -- How person_1 stands to person_2. A genuinely
                                                    -- OPEN set: no CHECK and no fixed TypeScript list,
                                                    -- because scripture's kinship vocabulary is wider
                                                    -- than any enum worth freezing. Tokens are
                                                    -- lower_snake_case. Shipped vocabulary:
                                                    --   Family    'father_of', 'mother_of', 'son_of',
                                                    --             'daughter_of', 'husband_of',
                                                    --             'wife_of', 'brother_of',
                                                    --             'sister_of', 'ancestor_of',
                                                    --             'descendant_of'
                                                    --   Social    'servant_of', 'master_of',
                                                    --             'disciple_of', 'teacher_of',
                                                    --             'ally_of', 'enemy_of',
                                                    --             'successor_of'
                                                    -- Direction matters -- 'father_of' read the other
                                                    -- way is relationship_type_reciprocal.
    relationship_type_reciprocal TEXT,              -- Type as read from person 2 to person 1
    confidence                   TEXT,              -- How firmly scripture establishes the
                                                    -- relationship. Open set, no CHECK:
                                                    --   'certain'   Stated plainly in the text
                                                    --   'probable'  Strongly implied
                                                    --   'possible'  Supportable but not established
                                                    --   'disputed'  Interpreters disagree
                                                    --   'derived'   Inferred by the build, not by a
                                                    --               reader -- machine-generated
                                                    -- NULL = unrated, not 'certain'.
    notes                        TEXT                -- Prose, typically the passage establishing it
);

CREATE INDEX idx_person_relationship_p1 ON person_relationship(person_1_id);
CREATE INDEX idx_person_relationship_p2 ON person_relationship(person_2_id);

