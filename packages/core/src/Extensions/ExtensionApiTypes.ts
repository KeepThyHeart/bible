// --- INetworkApi *(T2)* ----------------------------------------------------

export interface INetworkApi {
  /**
   * Mediated outbound HTTP/HTTPS request. The URL's host MUST appear in the
   * extension's `network.allowedHosts` manifest entry; otherwise the call
   * rejects with `NetworkHostNotAllowedError` even if `network` permission is
   * granted.
   *
   * Private-network destinations (loopback, RFC1918, link-local) are blocked
   * by default. To target a private host, the extension must list a literal
   * IP or hostname in `allowedHosts` and the user must approve it explicitly
   * at install time (the consent dialog highlights private targets).
   */
  fetch(url: string, init?: NetworkFetchInit): Promise<NetworkFetchResponse>;

  /** True if the host is currently in the extension's allowlist. */
  isHostAllowed(host: string): Promise<boolean>;
}

// --- IAuthApi *(T2 - depends on INetworkApi)* ------------------------------

export interface IAuthApi {
  /**
   * Run the OAuth 2.0 Authorization Code flow (with PKCE by default). The
   * host opens a real BrowserWindow pointing at `authorizeUrl`, watches for
   * navigation to the redirect URI, captures the `code` and `state`, performs
   * the token exchange itself, and resolves with the result.
   *
   * The redirect URI is always `ext-ui://<extensionId>/<redirectPath>`,
   * registered with the auth provider. This means the host's custom protocol
   * receives the redirect - no public callback server required.
   *
   * Token storage is the extension's responsibility (use `storage:secrets`).
   */
  startOAuth(opts: StartOAuthOpts): Promise<OAuthResult>;

  /** Exchange a refresh_token for a new access_token. */
  refreshOAuth(opts: RefreshOAuthOpts): Promise<OAuthResult>;

  /**
   * Open the user's default browser at a URL (e.g. for a settings page on
   * the extension's website). Requires `network:oauth` permission.
   */
  openExternal(url: string): Promise<void>;
}

// --- ITasksApi *(T2)* ------------------------------------------------------

export interface ITasksApi {
  /**
   * Run a long-running task. The host invokes `workEndpoint` via reverse-RPC
   * with a `taskHandle` the worker uses to report progress and check for
   * cancellation. The host shows a progress entry in the status bar and a
   * notification on completion if `notifyOnComplete` is set.
   */
  run<T = void>(task: BackgroundTaskDescriptor): Promise<T>;

  /** Report progress for a running task. Called from inside the work handler. */
  reportProgress(taskHandle: string, update: TaskProgressUpdate): Promise<void>;

  /** True if the user has requested cancellation. The work handler should return early. */
  isCancellationRequested(taskHandle: string): Promise<boolean>;

  /** Cancel a running task by ID. */
  cancel(taskId: string): Promise<void>;

  /** List tasks owned by this extension. */
  list(): Promise<BackgroundTaskInfo[]>;
}

// --- IExtensionsApi *(T2)* -------------------------------------------------

/**
 * The narrow surface (no events, no streaming) is intentional. If two
 * extensions need a tighter coupling, they can both depend on a third
 * extension that owns the shared state.
 */
export interface IExtensionsApi {
  /**
   * Call a method another extension has exported via `contributes.apiExports`.
   * Requires `extensions:call` permission. The host validates the call against
   * the callee's manifest - undeclared methods reject with
   * `ApiExportNotFoundError`.
   *
   * Calls are mediated by the host (worker A -> host -> worker B) so neither
   * extension can crash the other. Arguments and return values must be
   * JSON-serializable.
   */
  call<T = unknown>(
    extensionId: string,
    method: string,
    args?: unknown[],
  ): Promise<T>;

  /** True if an extension is installed and active. */
  isActive(extensionId: string): Promise<boolean>;

  /** List extensions that export at least one API method. */
  listProviders(): Promise<ExtensionProviderInfo[]>;

  onDidActivate: IEventApi<{ extensionId: string }>;
  onDidDeactivate: IEventApi<{ extensionId: string }>;
}

// --- IAiApi (RESERVED) *(T1 stub - full surface is T3)* --------------------

