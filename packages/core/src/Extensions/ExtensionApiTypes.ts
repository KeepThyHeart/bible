/**
 * Root API object the host injects into each extension worker. The worker
 * receives an instance of this in its `activate(api)` entry point.
 *
 * Each namespace below is a thin RPC proxy generated by
 * `apps/desktop/extension-runtime/apiProxy.ts` - calling
 * `api.bible.getVerse(...)` from the worker emits an `RpcRequest` envelope
 * that the host's `ExtensionRpcRouter` dispatches to
 * `bibleApiImpl.getVerse(...)` after the permission guard runs.
 */
export interface BibleExtensionAPI {
  bible: IBibleApi;
  commentary: ICommentaryApi;
  book: IBookApi;
  dictionary: IDictionaryApi;
  notes: INotesApi;
  highlights: IHighlightsApi;
  bookmarks: IBookmarksApi;
  commands: ICommandsApi;
  ui: IUiApi;
  workspace: IWorkspaceApi;
  context: IContextApi;
  storage: IStorageApi;
  l10n: IL10nApi;
  events: IEventsApi;
  /** T2 - outbound HTTP, host-mediated. */
  network: INetworkApi;
  /** T2 - OAuth 2.0 / PKCE broker. */
  auth: IAuthApi;
  /** T2 - background tasks with progress. */
  tasks: ITasksApi;
  /** T2 - inter-extension method calls. */
  extensions: IExtensionsApi;
  /** RESERVED - provider-role plumbing only in v1. */
  ai: IAiApi;
}

// --- IBibleApi *(T1 - read methods are foundation; iterate/tokens are T2)* -

export interface IBibleApi {
  /** Get a single verse from the active or specified module. */
  getVerse(verseId: number, opts?: { module?: string }): Promise<BibleVerseDto>;

  /** Get a range of verses (inclusive). Max range size: 500 verses. */
  getRange(
    start: number,
    end: number,
    opts?: { module?: string },
  ): Promise<BibleVerseDto[]>;

  /** List installed Bible modules with metadata. */
  listModules(): Promise<BibleModuleInfoDto[]>;

  /** List the books in a Bible module (with chapter counts). */
  listBooks(moduleId?: string): Promise<BibleBookDto[]>;

  /**
   * Cursor-based iteration across verses. Required for extensions that need
   * to scan the corpus (custom indexes, embeddings, alignment data). Max page
   * size is 1000; the host may return fewer than requested. The host
   * guarantees stable iteration order across calls with the same opts.
   */
  iterateVerses(opts: IterateVersesOpts): Promise<VerseIterationResult>;

  /** Parse a reference string. Locale-aware. */
  parseReference(input: string, locale?: string): Promise<ParsedReferenceDto | null>;

  /**
   * Get token-level data for a verse if the module exposes it (interlinear,
   * Strong's, morphology). Returns null if the module has no token data.
   */
  getVerseTokens(
    verseId: number,
    opts?: { module?: string },
  ): Promise<VerseTokenDto[] | null>;

  /**
   * Programmatically navigate the primary Bible pane to a specific verse.
   * The host resolves after the renderer has processed the navigation
   * request and fires `onDidChangeActiveVerse` once the verse is visible.
   *
   * Requires `bible:read` permission (navigation is a read-adjacent action).
   */
  navigateToVerse(verseId: number): Promise<void>;

  /**
   * Register a custom Bible text provider. The host treats it as another
   * installed module. Requires `bible:provide` permission.
   */
  registerProvider(
    provider: BibleProviderDescriptor,
  ): Promise<DisposableHandle>;

  /** Stable event: the user navigated to a new active verse anywhere in the app. */
  onDidChangeActiveVerse: IEventApi<{ verseId: number; module: string } | null>;

  /** A token / word inside a verse was selected (click, double-click, or selection). */
  onDidSelectVerseWord: IEventApi<VerseWordSelection>;
}

