function parseLexicon(lines: string[]): Record<string, string[]> {
  const table: Record<string, string[]> = {};
  for (let i = 0; i < lines.length; i++) {
    const parts = lines[i].split(' ');
    table[parts[0]] = parts.slice(1);
  }
  return table;
}

