#!/usr/bin/env node
// Regenerates css/web-app.css and css/desktop-app.css from the apps' real
// stylesheets, so the wireframes stay in step with the apps.
//
//   node docs/wireframes/pane-menu/build-css.mjs <tool-dir>
//
// <tool-dir> is any folder with these npm packages installed (outside the repo):
//   tailwindcss@3.4.17 @tailwindcss/typography postcss postcss-import sass@1.80 dockview-core@5.1.0
//   @fortawesome/fontawesome-free@7.2.0
// The wireframes themselves are static HTML; nothing here runs in the apps.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const toolDir = path.resolve(process.argv[2] ?? '.');
const req = createRequire(path.join(toolDir, 'package.json'));
const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../..');
const out = path.join(here, 'css');
fs.mkdirSync(out, { recursive: true });

const sass = req('sass');
const postcss = req('postcss');
const atImport = req('postcss-import');
const tailwind = req('tailwindcss');

const uiCss = path.join(repo, 'packages/ui/css');
const resolveAlias = (id) => (id.startsWith('@bible/ui/css/') ? path.join(uiCss, id.slice('@bible/ui/css/'.length)) : id);

// --- Web: main.scss + the KTH map/classes, exactly as apps/web/src/main.tsx loads them.
const web = sass.compile(path.join(repo, 'apps/web/src/styles/main.scss'), { style: 'expanded', quietDeps: true, silenceDeprecations: ['import', 'global-builtin', 'color-functions', 'mixed-decls'] }).css;
const kthWeb = await postcss([atImport()]).process(
  `@import '${path.join(uiCss, 'generated/map-web.css')}';\n@import '${path.join(uiCss, 'kth.css')}';\n`,
  { from: path.join(uiCss, 'entry.css') });
fs.writeFileSync(path.join(out, 'web-app.css'), `/* GENERATED by build-css.mjs from apps/web/src/styles/main.scss + packages/ui/css. Do not edit. */\n${web}\n${kthWeb.css}`);

// --- Desktop: globals.css (themes, KTH, controls, Tailwind) + dockview's own CSS + dockview-overrides.css.
const desktopStyles = path.join(repo, 'apps/desktop/src/ui/styles');
const dockviewCss = req.resolve('dockview-core/dist/styles/dockview.css');
// The config require()s @tailwindcss/typography: let it resolve from <tool-dir>.
process.env.NODE_PATH = path.join(toolDir, 'node_modules');
req('node:module').Module._initPaths();
const baseConfig = (await import(path.join(repo, 'apps/desktop/tailwind.config.cjs'))).default;
const config = {
  ...baseConfig,
  content: [path.join(here, 'desktop*.html')],
  plugins: [req('@tailwindcss/typography')],
};
// fonts.css points at self-hosted font files; the wireframes use system fallbacks instead.
const globals = fs.readFileSync(path.join(desktopStyles, 'globals.css'), 'utf8').replace(/@import '\.\/fonts\.css';/, '');
const entry = `${globals}\n@import '${dockviewCss}';\n@import '${path.join(desktopStyles, 'dockview-overrides.css')}';\n@import '${path.join(desktopStyles, 'controls.css')}';\n`;
const desk = await postcss([atImport({ resolve: resolveAlias, path: [desktopStyles] }), tailwind(config)])
  .process(entry, { from: path.join(desktopStyles, 'globals.css') });
fs.writeFileSync(path.join(out, 'desktop-app.css'), `/* GENERATED by build-css.mjs from apps/desktop/src/ui/styles + tailwind.config.cjs + dockview-core. Do not edit. */\n${desk.css}`);

// --- Font Awesome (the web app's icon set), vendored so the pages open offline.
const fa = path.dirname(req.resolve('@fortawesome/fontawesome-free/package.json'));
fs.mkdirSync(path.join(here, 'vendor/fontawesome/css'), { recursive: true });
fs.mkdirSync(path.join(here, 'vendor/fontawesome/webfonts'), { recursive: true });
for (const f of ['fontawesome.min.css', 'solid.min.css']) fs.copyFileSync(path.join(fa, 'css', f), path.join(here, 'vendor/fontawesome/css', f));
fs.copyFileSync(path.join(fa, 'webfonts/fa-solid-900.woff2'), path.join(here, 'vendor/fontawesome/webfonts/fa-solid-900.woff2'));
console.log('wrote css/web-app.css, css/desktop-app.css, vendor/fontawesome');
